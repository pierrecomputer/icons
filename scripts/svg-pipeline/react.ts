import type { ManifestAxis, ManifestIcon } from './manifest';

const SVG_PASSTHROUGH =
  "Omit<SVGAttributes<SVGSVGElement>, 'color' | 'style' | 'className' | 'width' | 'height'>";

export interface ReactVariant {
  key: string;
  viewBox: string;
  overflow: boolean;
  body: string;
  scopedIds: boolean;
}

function propType(axis: ManifestAxis): string {
  return axis.values
    .map((value) => (axis.numeric ? value.prop : JSON.stringify(value.prop)))
    .join(' | ');
}

function propDefault(axis: ManifestAxis): string {
  return axis.numeric ? axis.defaultValue : JSON.stringify(axis.defaultValue);
}

function propsInterface(icon: ManifestIcon): string {
  const heading =
    `export interface ${icon.name}Props\n` +
    `  extends IconProps,\n    ${SVG_PASSTHROUGH}`;
  if (icon.axes.length === 0) return `${heading} {}`;
  const members = icon.axes.map(
    (axis) =>
      `  /** @default ${propDefault(axis)} */\n` +
      `  ${axis.prop}?: ${propType(axis)};`
  );
  return `${heading} {\n${members.join('\n')}\n}`;
}

function bodyExpression(variant: ReactVariant, anyScoped: boolean): string {
  if (!anyScoped) return variant.body;
  const parameter = variant.scopedIds ? 'uid: string' : '';
  return `(${parameter}) => (${variant.body})`;
}

function variantRecord(variants: ReactVariant[]): string {
  const anyScoped = variants.some((variant) => variant.scopedIds);
  const anyOverflow = variants.some((variant) => variant.overflow);
  const entries = variants
    .map(
      (variant) =>
        `  ${JSON.stringify(variant.key)}: {\n` +
        `    viewBox: ${JSON.stringify(variant.viewBox)},\n` +
        (anyOverflow ? `    overflow: ${variant.overflow},\n` : '') +
        `    body: ${bodyExpression(variant, anyScoped)},\n` +
        `  },`
    )
    .join('\n');
  return `const variants = {\n${entries}\n};`;
}

function svgElement(anyOverflow: boolean, anyScoped: boolean): string {
  const body = anyScoped ? 'variant.body(uid)' : 'variant.body';
  const overflow = anyOverflow
    ? `, ...(variant.overflow ? { overflow: "visible" } : null)`
    : '';
  return [
    `    <svg`,
    `      xmlns="http://www.w3.org/2000/svg"`,
    `      fill="none"`,
    `      viewBox={variant.viewBox}`,
    `      width={size}`,
    `      height={size}`,
    `      style={{ ...style, color: Colors[color] ?? color${overflow} }}`,
    '      className={`pi${className != null ? ` ${className}` : ``}`}',
    `      {...props}`,
    `    >`,
    `      {${body}}`,
    `    </svg>`,
  ].join('\n');
}

export function generateReactIcon(
  icon: ManifestIcon,
  variants: ReactVariant[]
): string {
  const anyScoped = variants.some((variant) => variant.scopedIds);
  const anyOverflow = variants.some((variant) => variant.overflow);
  const sizeAxis = icon.axes.find(
    (axis) => axis.prop === 'size' && axis.numeric
  );
  const signature = [
    ...icon.axes.map((axis) => `  ${axis.prop} = ${propDefault(axis)},`),
    ...(sizeAxis ? [] : ['  size = 16,']),
    `  color = "currentcolor",`,
    `  style,`,
    `  className,`,
    `  ...props`,
  ].join('\n');
  const key =
    icon.axes.length === 0
      ? JSON.stringify(variants[0]?.key ?? 'default')
      : `\`${icon.axes.map((axis) => `\${${axis.prop}}`).join('-')}\``;
  const imports = anyScoped
    ? `import { type SVGAttributes, useId } from 'react';`
    : `import type { SVGAttributes } from 'react';`;

  return [
    `// Generated by \`npm run icons:build\`, do not edit manually.`,
    imports,
    ``,
    `import { Colors, type IconProps } from '../types.js';`,
    ``,
    propsInterface(icon),
    ``,
    variantRecord(variants),
    ``,
    `export function ${icon.name}({`,
    signature,
    `}: ${icon.name}Props) {`,
    ...(anyScoped
      ? [`  const uid = useId().replace(/[^a-zA-Z0-9_-]/g, "");`]
      : []),
    `  const key = ${key} as keyof typeof variants;`,
    `  const variant = variants[key];`,
    ``,
    `  return (`,
    svgElement(anyOverflow, anyScoped),
    `  );`,
    `}`,
    ``,
  ].join('\n');
}

export function generateReactIndex(icons: ManifestIcon[]): string {
  const exports = Array.from(new Set(icons.map((icon) => icon.name)))
    .sort()
    .map((name) => `export { ${name}, type ${name}Props } from './${name}.js';`)
    .join('\n');
  return `// Generated by \`npm run icons:build\`, do not edit manually.\n${exports}\n`;
}
